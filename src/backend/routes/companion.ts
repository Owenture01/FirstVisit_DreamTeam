import { Router, type Request, type Response } from 'express';
import { ThinkingLevel } from '@google/genai';
import { getGeminiClient } from '../services/geminiClient.ts';
import {
  buildHanaSystemInstruction,
  detectElevatedBPWithoutSevereSymptoms,
  detectRedFlagEmergency,
  EMERGENCY_STANDARD_REPLY,
  type LoggedMedicationContext,
  parseHanaResponse,
  TRIGGER_HELP_TOKEN,
} from '../utils/hanaSafety.ts';
import {
  classifyGeminiError,
  executeCompanionWithFallback,
} from '../utils/geminiRetry.ts';

export const companionRouter = Router();

interface IncomingHistoryMessage {
  sender: 'user' | 'hana';
  text: string;
}

interface CompanionChatBody {
  message?: string;
  history?: IncomingHistoryMessage[];
  mode?: 'daily' | 'mental_health';
  gestationalWeek?: number;
  gestationalDay?: number;
  memoryTopic?: string;
  loggedMedications?: LoggedMedicationContext[];
  vitals?: {
    bp?: string;
    heartRate?: number;
    fetalHeartRate?: number;
  };
}

// Proactive tips generated by AI companion Hana based on vitals stream
companionRouter.get('/proactive-tip/:patientId', (_req: Request, res: Response) => {
  res.json({
    companion: 'Hana · AI helper',
    tipId: 'tip-sleep-hydration',
    headline: 'Only 5 h of sleep. Want a tip?',
    detail:
      'Short sleep increases maternal blood pressure variability. A 20-minute afternoon rest with elevated feet will restore placental perfusion.',
    actions: {
      primary: 'Yes please',
      secondary: 'Later',
    },
  });
});

// Clinical-safe AI Companion chat endpoint backed by Gemini on the server
companionRouter.post('/chat', async (req: Request, res: Response) => {
  const body = (req.body || {}) as CompanionChatBody;
  const message = typeof body.message === 'string' ? body.message.trim() : '';

  if (!message) {
    res.status(400).json({
      error: 'Please enter a message for Hana.',
      code: 'EMPTY_MESSAGE',
    });
    return;
  }

  // 1. Deterministic red-flag emergency safety check (immediate clinical takeover)
  const redFlag = detectRedFlagEmergency(message);
  if (redFlag.triggered) {
    res.status(200).json({
      reply: EMERGENCY_STANDARD_REPLY,
      rawReply: `${EMERGENCY_STANDARD_REPLY} ${TRIGGER_HELP_TOKEN}`,
      triggerHelpTakeover: true,
      redFlagReason: redFlag.reason,
      matchedSymptom: redFlag.matchedSymptom,
      matchedSymptoms: redFlag.matchedSymptoms,
      detectedBP: redFlag.detectedBP,
    });
    return;
  }

  // 2. Initialize Gemini client on server
  const ai = getGeminiClient();
  if (!ai) {
    res.status(503).json({
      error:
        'Hana cannot connect to the AI service right now because the server GEMINI_API_KEY is not configured. If you feel unwell, please press Help.',
      code: 'MISSING_API_KEY',
    });
    return;
  }

  // 3. Build clinical guardrail system instruction + check borderline elevated BP
  const elevatedBP = detectElevatedBPWithoutSevereSymptoms(message);
  let systemInstruction = buildHanaSystemInstruction({
    patientName: 'Mariam',
    gestationalWeek: body.gestationalWeek,
    gestationalDay: body.gestationalDay,
    memoryTopic: body.memoryTopic,
    mode: body.mode === 'mental_health' ? 'mental_health' : 'daily',
    loggedMedications: Array.isArray(body.loggedMedications) ? body.loggedMedications : undefined,
    vitals: body.vitals,
  });

  if (elevatedBP) {
    systemInstruction += `\n\nURGENT CONTEXT DETECTED: Mariam just shared a blood pressure reading of ${elevatedBP.bpString} mmHg (140/90 to 159/109 range) without severe associated symptoms mentioned yet. Advise her clearly to contact her clinic or midwife today for an urgent blood pressure evaluation and urine test, and ask if she has any headache, blurry vision, or upper abdominal pain.`;
  }

  // Map prior conversation turns into alternating user/model Gemini contents starting with user
  const rawHistory = Array.isArray(body.history) ? body.history.slice(-10) : [];
  const mergedHistory: Array<{ role: 'user' | 'model'; text: string }> = [];

  for (const item of rawHistory) {
    if (!item || typeof item.text !== 'string' || !item.text.trim()) continue;
    const role: 'user' | 'model' = item.sender === 'user' ? 'user' : 'model';
    const clean = item.text.trim();
    const prev = mergedHistory[mergedHistory.length - 1];
    if (prev && prev.role === role) {
      prev.text = `${prev.text}\n${clean}`;
    } else {
      mergedHistory.push({ role, text: clean });
    }
  }

  // Drop leading model turn if history started with Hana's greeting
  while (mergedHistory.length > 0 && mergedHistory[0].role === 'model') {
    mergedHistory.shift();
  }

  // Ensure the final turn is the current user message
  const lastMerged = mergedHistory[mergedHistory.length - 1];
  if (!lastMerged || lastMerged.role !== 'user' || !lastMerged.text.endsWith(message)) {
    if (lastMerged && lastMerged.role === 'user') {
      lastMerged.text = `${lastMerged.text}\n${message}`;
    } else {
      mergedHistory.push({ role: 'user', text: message });
    }
  }

  const contents = mergedHistory.map((turn) => ({
    role: turn.role,
    parts: [{ text: turn.text }],
  }));

  try {
    const { text: rawText, modelUsed } = await executeCompanionWithFallback(
      async ({ model, useLowThinking }) => {
        const timeoutMs = 9500;
        const abortSignal = AbortSignal.timeout(timeoutMs);
        const response = await ai.models.generateContent({
          model,
          contents,
          config: useLowThinking
            ? {
                systemInstruction,
                thinkingConfig: { thinkingLevel: ThinkingLevel.LOW },
                abortSignal,
                httpOptions: { timeout: timeoutMs },
              }
            : {
                systemInstruction,
                abortSignal,
                httpOptions: { timeout: timeoutMs },
              },
        });
        return (response.text ?? '').trim();
      },
      { attemptsPerModel: 2, baseDelayMs: 600 }
    );

    const parsed = parseHanaResponse(rawText);

    res.status(200).json({
      reply: parsed.cleanText,
      rawReply: rawText,
      modelUsed,
      triggerHelpTakeover: parsed.triggerHelpTakeover,
      elevatedBpNotice: Boolean(elevatedBP),
      detectedBP: elevatedBP?.bpString,
    });
  } catch (err: unknown) {
    const errorMessage = err instanceof Error ? err.message : String(err);
    console.error('Gemini companion chat error:', errorMessage);

    const classified = classifyGeminiError(errorMessage);
    res.status(classified.httpStatus).json({
      error: classified.userMessage,
      code: classified.code,
    });
  }
});
